create policy "members can read organizations" on public.organizations for select to authenticated
using (public.runlu_is_org_member(id));
create policy "authenticated users can create organizations" on public.organizations for insert to authenticated
with check (created_by = auth.uid());
create policy "owners admins can update organizations" on public.organizations for update to authenticated
using (public.runlu_has_org_role(id,array['owner','admin']))
with check (public.runlu_has_org_role(id,array['owner','admin']));

create policy "members can read organization membership" on public.organization_members for select to authenticated
using (public.runlu_is_org_member(organization_id));
create policy "owners admins can add members" on public.organization_members for insert to authenticated
with check (public.runlu_has_org_role(organization_id,array['owner','admin']));
create policy "owners admins can update members" on public.organization_members for update to authenticated
using (public.runlu_has_org_role(organization_id,array['owner','admin']))
with check (public.runlu_has_org_role(organization_id,array['owner','admin']));
create policy "owners admins can remove members" on public.organization_members for delete to authenticated
using (public.runlu_has_org_role(organization_id,array['owner','admin']));

create policy "members can read warehouses" on public.warehouses for select to authenticated
using (public.runlu_is_org_member(organization_id));
create policy "managers can create warehouses" on public.warehouses for insert to authenticated
with check (public.runlu_has_org_role(organization_id,array['owner','admin','manager']));
create policy "managers can update warehouses" on public.warehouses for update to authenticated
using (public.runlu_has_org_role(organization_id,array['owner','admin','manager']))
with check (public.runlu_has_org_role(organization_id,array['owner','admin','manager']));

create policy "members can read tenant datasets" on public.tenant_datasets for select to authenticated
using (public.runlu_is_org_member(organization_id));
create policy "members can create tenant datasets" on public.tenant_datasets for insert to authenticated
with check (public.runlu_is_org_member(organization_id) and updated_by = auth.uid());
create policy "members can update tenant datasets" on public.tenant_datasets for update to authenticated
using (public.runlu_is_org_member(organization_id))
with check (public.runlu_is_org_member(organization_id) and updated_by = auth.uid());
create policy "managers can delete tenant datasets" on public.tenant_datasets for delete to authenticated
using (public.runlu_has_org_role(organization_id,array['owner','admin','manager']));

create policy "members can read audit events" on public.audit_events for select to authenticated
using (public.runlu_is_org_member(organization_id));
create policy "members can append audit events" on public.audit_events for insert to authenticated
with check (public.runlu_is_org_member(organization_id) and actor_user_id = auth.uid());

