for each row execute function public.runlu_set_updated_at();

drop trigger if exists warehouses_updated_at on public.warehouses;
create trigger warehouses_updated_at before update on public.warehouses
for each row execute function public.runlu_set_updated_at();

drop trigger if exists tenant_datasets_updated_at on public.tenant_datasets;
create trigger tenant_datasets_updated_at before update on public.tenant_datasets
for each row execute function public.runlu_set_updated_at();

-- SECURITY DEFINER helpers avoid recursive RLS checks on organization_members.
create or replace function public.runlu_is_org_member(target_org uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.organization_members m
    where m.organization_id = target_org and m.user_id = auth.uid() and m.status = 'active'
  );
$$;

create or replace function public.runlu_has_org_role(target_org uuid, allowed_roles text[])
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.organization_members m
    where m.organization_id = target_org and m.user_id = auth.uid()
      and m.status = 'active' and m.role = any(allowed_roles)
  );
$$;

-- Atomic self-service onboarding. Creates organization + owner membership + first warehouse
-- in one transaction so there is never a tenant with no owner.
create or replace function public.runlu_create_organization(
  p_name text,
  p_slug text,
  p_warehouse_name text default 'Main Warehouse',
  p_warehouse_code text default 'MAIN',
  p_website_url text default null,
  p_support_email text default null,
  p_currency text default 'USD',
  p_locale text default 'en',
  p_timezone text default 'UTC',
  p_warehouse_settings jsonb default '{}'::jsonb
)
returns table (organization_id uuid, warehouse_id uuid)
language plpgsql security definer set search_path = '' as $$
declare
  v_user uuid := auth.uid();
  v_org uuid;
  v_warehouse uuid;
begin
  if v_user is null then raise exception 'Authentication required'; end if;
  if nullif(trim(p_name),'') is null then raise exception 'Organization name is required'; end if;
  if nullif(trim(p_slug),'') is null then raise exception 'Organization slug is required'; end if;
  if nullif(trim(p_warehouse_name),'') is null then raise exception 'Warehouse name is required'; end if;
  if nullif(trim(p_warehouse_code),'') is null then raise exception 'Warehouse code is required'; end if;

  insert into public.organizations (
    name, slug, website_url, support_email, default_currency, default_locale,
    timezone, plan_code, trial_ends_at, created_by
  ) values (
    trim(p_name), lower(trim(p_slug)), nullif(trim(p_website_url),''), nullif(trim(p_support_email),''),
    upper(trim(coalesce(p_currency,'USD'))), lower(trim(coalesce(p_locale,'en'))),
    trim(coalesce(p_timezone,'UTC')), 'trial', now() + interval '14 days', v_user
  ) returning id into v_org;

  insert into public.organization_members (organization_id, user_id, role, status)
  values (v_org, v_user, 'owner', 'active');

  insert into public.warehouses (organization_id, name, code, settings)
  values (v_org, trim(p_warehouse_name), upper(trim(p_warehouse_code)), coalesce(p_warehouse_settings,'{}'::jsonb))
  returning id into v_warehouse;

  insert into public.audit_events (organization_id, warehouse_id, actor_user_id, event_type, entity_type, entity_id, payload)
  values (v_org, v_warehouse, v_user, 'workspace.created', 'organization', v_org::text,
    jsonb_build_object('warehouse_id',v_warehouse,'plan_code','trial'));

  return query select v_org, v_warehouse;
end;
$$;

