import assert from 'node:assert/strict';
const open=t=>!['Completed','Cancelled'].includes(String(t.status||'Waiting'));
const verbs=t=>t.task_type==='Carpet Cutting'?{start:'Start Cutting',done:'Cut Complete'}:{start:'Start Picking',done:'Prepared'};
const actions=t=>{const s=t.status||'Waiting',v=verbs(t),a=[];if(['Completed','Cancelled'].includes(s))return a;if(s==='Waiting')a.push(v.start);if(['In Progress','Partial'].includes(s))a.push('Partial',v.done);return a};
const route=t=>({location:t.location||'',ref:t.task_type==='Carpet Cutting'?(t.roll_number||''):(t.item_name||''),quantity:t.quantity,unit:t.unit});
let n=0;const ok=f=>{f();n++};
const pick={task_type:'Stock Picking',status:'Waiting',item_name:'HC',location:'9',quantity:4,unit:'ROLL'};
const cut={task_type:'Carpet Cutting',status:'Waiting',item_name:'Carpet',roll_number:'R100',location:'3B',quantity:18.5,unit:'LF'};
ok(()=>assert.deepEqual(actions(pick),['Start Picking']));
ok(()=>assert.deepEqual(actions(cut),['Start Cutting']));
pick.status='In Progress';cut.status='In Progress';
ok(()=>assert.deepEqual(actions(pick),['Partial','Prepared']));
ok(()=>assert.deepEqual(actions(cut),['Partial','Cut Complete']));
ok(()=>assert.deepEqual(route(cut),{location:'3B',ref:'R100',quantity:18.5,unit:'LF'}));
ok(()=>assert.deepEqual(route(pick),{location:'9',ref:'HC',quantity:4,unit:'ROLL'}));
ok(()=>assert.equal(open({status:'Partial'}),true));
ok(()=>assert.equal(open({status:'Completed'}),false));
ok(()=>assert.equal(open({status:'Cancelled'}),false));
ok(()=>assert.deepEqual(actions({task_type:'Carpet Cutting',status:'Completed'}),[]));
console.log(`Warehouse Build116 material work board: ${n}/${n} PASS`);
console.log('Board is execution-status only; physical inventory posting remains in existing Warehouse workflows.');
